function Card({ title, children, variant = 'default' }) {
  const bgClass = variant === 'success' ? 'bg-green-500/10 border-green-500/30' :
                  variant === 'warning' ? 'bg-yellow-500/10 border-yellow-500/30' :
                  variant === 'info' ? 'bg-blue-500/10 border-blue-500/30' :
                  'bg-white/5 border-white/10';

  return (
    <div className={`${bgClass} border rounded-xl p-5 mb-4`}>
      {title && <h3 className="text-white font-bold mb-2">{title}</h3>}
      <div className="text-white/70 text-sm leading-relaxed space-y-2">
        {children}
      </div>
    </div>
  );
}

