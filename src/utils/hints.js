// Система подсказок — хранение в localStorage

const KEY_ENABLED  = 'hintsEnabled';
const KEY_DISMISSED = 'hintsDismissed';

export function hintsEnabled() {
  return localStorage.getItem(KEY_ENABLED) !== 'false';
}

export function setHintsEnabled(val) {
  localStorage.setItem(KEY_ENABLED, val ? 'true' : 'false');
}

export function isDismissed(key) {
  if (!hintsEnabled()) return true;
  try {
    return JSON.parse(localStorage.getItem(KEY_DISMISSED) || '[]').includes(key);
  } catch { return false; }
}

export function dismiss(key) {
  try {
    const list = JSON.parse(localStorage.getItem(KEY_DISMISSED) || '[]');
    if (!list.includes(key)) localStorage.setItem(KEY_DISMISSED, JSON.stringify([...list, key]));
  } catch {}
}

