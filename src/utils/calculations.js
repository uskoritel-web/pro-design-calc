// Логика расчёта стоимости мебели

// Форматирование суммы в рубли
export const fmt = (n) =>
  new Intl.NumberFormat('ru-RU').format(Math.round(n || 0)) + ' ₽';

// Расчёт количества листов ЛДСП.
// Коэффициенты нормализуем и защищаемся от 0/пустой строки/запятой —
// иначе деление даёт Infinity и вся смета превращается в «∞».
export function calcSheets(нижняя, верхняя, пеналы, коэфНиз, коэфВерх) {
  const кНиз  = parseFloat(String(коэфНиз ?? '').replace(',', '.'))  || 1.8;
  const кВерх = parseFloat(String(коэфВерх ?? '').replace(',', '.')) || 3.0;
  const листыНиз  = нижняя  > 0 ? Math.ceil(нижняя  / кНиз)  : 0;
  const листыВерх = верхняя > 0 ? Math.ceil(верхняя / кВерх) : 0;
  return пеналы + листыНиз + листыВерх;
}

// Подбор оптимального раскроя столешницы из листов 3050 и 4200 мм.
// Условие: каждый кусок ≥ минКусок мм (по умолч. 500 мм).
// Критерий: минимальная закупочная стоимость, при равной — меньше швов.
export function calcTableTopCutting(нужнаяДлинаМм, столешницы) {
  const L = Math.round(parseFloat(нужнаяДлинаМм) || 0);
  if (L <= 0) return null;

  const МИН    = Math.round(parseFloat(столешницы?.минКусок)   || 500);
  const C3050  = parseFloat(столешницы?.закупка3050) || 0;
  const C4200  = parseFloat(столешницы?.закупка4200) || 0;
  const Н      = parseFloat(столешницы?.наценка)     || 0;
  const Л3050  = 3050;
  const Л4200  = 4200;

  if (L < МИН) return { error: `Минимальная длина — ${МИН} мм` };

  let лучший = null;
  // Максимально нужных листов — L / МИН (каждый минимального размера)
  const maxN = Math.min(Math.ceil(L / МИН) + 2, 20);

  for (let n1 = 0; n1 <= maxN; n1++) {
    for (let n2 = 0; n2 <= maxN - n1; n2++) {
      if (n1 + n2 === 0) continue;
      const T = n1 * Л3050 + n2 * Л4200;
      if (T < L) continue;                         // не хватает материала
      if (L < (n1 + n2) * МИН) continue;          // куски не влезут в минимум

      const cost   = n1 * C3050 + n2 * C4200;
      const sheets = n1 + n2;
      const лучше  = !лучший
        || cost < лучший.cost
        || (cost === лучший.cost && sheets < лучший.sheets);

      if (лучше) лучший = { n1, n2, T, sheets, cost };
    }
  }

  if (!лучший) return { error: 'Не удалось подобрать раскрой' };

  // Раскладываем L на куски для отображения
  const sizes = [
    ...Array(лучший.n1).fill(Л3050),
    ...Array(лучший.n2).fill(Л4200),
  ].sort((a, b) => b - a);

  const pieces = [];
  let rem = L;
  for (let i = 0; i < sizes.length; i++) {
    if (i === sizes.length - 1) {
      pieces.push({ sheet: sizes[i], piece: rem, waste: sizes[i] - rem });
    } else {
      const rest    = sizes.length - i - 1;
      const maxRest = sizes.slice(i + 1).reduce((s, x) => s + x, 0);
      const min     = Math.max(МИН, rem - maxRest);
      const max     = Math.min(sizes[i], rem - rest * МИН);
      const p       = Math.round(Math.min(max, Math.max(min, rem / (rest + 1))));
      pieces.push({ sheet: sizes[i], piece: p, waste: sizes[i] - p });
      rem -= p;
    }
  }

  return {
    n1: лучший.n1,
    n2: лучший.n2,
    sheets: лучший.sheets,
    joints: лучший.sheets - 1,
    cost: лучший.cost,
    costКлиент: Math.round(лучший.cost * (1 + Н / 100)),
    pieces,
  };
}

// Вычислить сумму наценки или скидки по типу и значению
function calcAdjustment(base, тип, значение) {
  if (тип === 'percent' && значение > 0) return base * (значение / 100);
  if (тип === 'sum' && значение > 0) return значение;
  return 0;
}

// Нормализация числа из поля ввода: строка с запятой/пробелами → число.
const num = (v) => parseFloat(String(v ?? '').replace(',', '.').replace(/\s/g, '')) || 0;

// Полный расчёт по всем блокам.
// В результат добавляется массив `предупреждения` — позиции, которые
// молча дают 0 ₽ (незаполненная цена). Форма использует его, чтобы не
// отправить клиенту заниженное КП.
export function calcTotal(data, settings) {
  const предупреждения = [];
  const нижняя = num(data.нижняя);
  const верхняя = num(data.верхняя);
  const пеналы = parseInt(data.пеналы) || 0;

  // ── Корпуса ──
  const листы = (нижняя > 0 || верхняя > 0 || пеналы > 0)
    ? calcSheets(нижняя, верхняя, пеналы, settings.коэфНиз, settings.коэфВерх)
    : 0;
  const ценаЛиста = num(settings.ценаЛиста);
  if (листы > 0 && ценаЛиста <= 0) предупреждения.push('Не заполнена цена листа ЛДСП');
  const корпуса = листы * ценаЛиста;

  // ── Фасады ──
  const фасадыСумма = (data.фасады || []).reduce((sum, f) => {
    return sum + num(f.площадь) * num(f.цена);
  }, 0);

  // ── Фрезеровка ──
  const фрезеровка = data.фрезеровкаВкл
    ? num(data.фрезеровкаОбъём) * num(data.фрезеровкаЦена)
    : 0;

  // ── Столешница ──
  let столешница = 0;
  if (data.столешницаРежим === 'calc') {
    const tt = calcTableTopCutting(data.столешницаДлина, settings.столешницы);
    столешница = (tt && !tt.error) ? tt.costКлиент : 0;
    if (num(data.столешницаДлина) > 0 && столешница <= 0) {
      предупреждения.push('Столешница не рассчитана (проверьте длину и закупочные цены листов в настройках)');
    }
  } else {
    столешница = num(data.столешница);
  }

  // ── Дополнительно по столешницам ──
  const каменьБелыйМетры = num(data.каменьБелыйМетры);
  const каменьБелый = каменьБелыйМетры * num(settings.столешницы?.каменьБелый);

  const мойкаКамень = num(data.мойкаКамень) * num(settings.столешницы?.мойкаКамень);
  const подклейкаМойки = num(data.подклейкаМойки) * num(settings.столешницы?.подклейкаМойки);
  const подклейка = num(data.подклейка) * num(settings.столешницы?.подклейка);

  const допСтолешницы = каменьБелый + мойкаКамень + подклейкаМойки + подклейка;

  // ── Фурнитура ──
  // Режим 'бренд' — фиксированная сумма выбранного бренда (data.фурнитура).
  // Иначе считаем по позициям; при отсутствии позиций — тоже фикс. сумма.
  const hasPositions = (data.фурнитураПозиции || []).some(p => num(p.количество) > 0);
  let фурнитура;
  if (data.фурнитураРежим === 'бренд') {
    фурнитура = num(data.фурнитура);
  } else if (hasPositions) {
    фурнитура = data.фурнитураПозиции.reduce((sum, pos) => {
      const кол = num(pos.количество);
      if (кол <= 0) return sum;
      const priceItem = (settings.прайсФурнитуры || []).find(p => p.id === pos.id);
      const цена = num(priceItem?.цена);
      if (цена <= 0) {
        предупреждения.push(`Не заполнена цена: ${priceItem?.название || pos.id}`);
      }
      return sum + кол * цена;
    }, 0);
  } else {
    фурнитура = num(data.фурнитура);
  }

  const итогоМебель = корпуса + фасадыСумма + фрезеровка + столешница + допСтолешницы + фурнитура;

  const доставка  = num(data.доставка);
  const технолог  = num(data.технолог);

  // Монтаж считается от суммы материалов + технолог (без доставки)
  const baseBezMontazha = итогоМебель + технолог;
  const монтажПроцент = num(data.монтажПроцент);
  const монтаж = baseBezMontazha * (монтажПроцент / 100);

  const baseTotal = baseBezMontazha + монтаж + доставка;

  // ── Скрытая наценка ──────────────────────────────────────────────────────
  const скрытаяСумма = calcAdjustment(
    baseTotal,
    data.наценкаСкрытаяТип,
    num(data.наценкаСкрытая)
  );
  const скрМульт = baseTotal > 0 ? (baseTotal + скрытаяСумма) / baseTotal : 1;

  const кпКорпуса    = корпуса      * скрМульт;
  const кпФасады     = фасадыСумма  * скрМульт;
  const кпФрезеровка = фрезеровка   * скрМульт;
  const кпСтолешница = столешница   * скрМульт;
  const кпФурнитура  = фурнитура    * скрМульт;
  const кпМонтаж     = монтаж       * скрМульт;
  const кпДоставка   = доставка     * скрМульт;
  const кпТехнолог   = технолог     * скрМульт;
  const кпBase       = baseTotal    * скрМульт;

  // ── Видимая наценка ──────────────────────────────────────────────────────
  const видимаяСумма = calcAdjustment(
    кпBase,
    data.наценкаВидимаяТип,
    num(data.наценкаВидимая)
  );

  // ── Скидка ───────────────────────────────────────────────────────────────
  const скидкаСумма = calcAdjustment(
    кпBase + видимаяСумма,
    data.скидкаТип,
    num(data.скидка)
  );

  // Клиентская цена не может быть отрицательной (скидка больше суммы)
  const итогоКлиент = Math.max(0, кпBase + видимаяСумма - скидкаСумма);

  // ── Финансы ──────────────────────────────────────────────────────────────
  const себестоимостьВвод = String(data.себестоимость ?? '').trim();
  const себестоимость = себестоимостьВвод === '' ? null : num(data.себестоимость);
  const маржа = себестоимость !== null ? итогоКлиент - себестоимость : null;
  const маржаПроцент = маржа !== null && итогоКлиент > 0
    ? (маржа / итогоКлиент * 100).toFixed(1)
    : null;

  return {
    листы, корпуса,
    фасады: фасадыСумма,
    фрезеровка, столешница, допСтолешницы, фурнитура,
    каменьБелый, мойкаКамень, подклейкаМойки, подклейка,
    итогоМебель, монтаж, монтажПроцент, доставка, технолог,
    baseTotal, скрытаяСумма,
    кпКорпуса, кпФасады, кпФрезеровка, кпСтолешница, кпФурнитура,
    кпМонтаж, кпДоставка, кпТехнолог, кпBase, скрМульт,
    видимаяСумма, скидкаСумма, итогоКлиент,
    себестоимость, маржа, маржаПроцент,
    предупреждения,
    итого: baseTotal,
    итогоСНаценкой: итогоКлиент,
  };
}
