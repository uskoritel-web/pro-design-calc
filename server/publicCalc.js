// Готовит безопасную версию расчёта для ПУБЛИЧНОЙ страницы КП (клиент).
// Вырезает коммерческую тайну: себестоимость, маржу, скрытую наценку,
// множитель наценки. Цены фасадов заранее умножает на скрытый множитель,
// чтобы клиент не мог вычислить наценку.

// Поля result, которые безопасно показать клиенту (уже с учётом наценки)
const SAFE_RESULT = [
  'листы', 'корпуса', 'фасады', 'фрезеровка', 'столешница', 'допСтолешницы',
  'фурнитура', 'каменьБелый', 'мойкаКамень', 'подклейкаМойки', 'подклейка',
  'итогоМебель', 'монтаж', 'монтажПроцент', 'доставка', 'технолог',
  'кпКорпуса', 'кпФасады', 'кпФрезеровка', 'кпСтолешница', 'кпФурнитура',
  'кпМонтаж', 'кпДоставка', 'кпТехнолог', 'кпBase',
  'видимаяСумма', 'скидкаСумма', 'итогоКлиент', 'итогоСНаценкой',
];

// Верхнеуровневые поля расчёта, которые видит клиент
const SAFE_TOP = [
  'id', 'клиент', 'объект', 'заголовокКП', 'изображение',
  'нижняя', 'верхняя', 'пеналы',
  'фрезеровкаВкл', 'фрезеровкаОбъём',
  'столешницаМатериал', 'столешницаРежим', 'столешницаДлина',
  'фурнитураБренд', 'фурнитураРежим',
  'срокДействия', 'срокДоставкиДней', 'датаПроизводства', 'createdAt',
  'трекингВкл', 'подтверждениеВкл', 'таймерВкл', 'опросВкл',
];

function toPublic(row) {
  const data = row.data || {};
  const result = data.result || {};
  const скрМульт = Number(result.скрМульт) || 1;

  const safeResult = {};
  for (const k of SAFE_RESULT) {
    if (result[k] !== undefined) safeResult[k] = result[k];
  }
  // Множитель скрытой наценки клиенту не отдаём; кп*-поля уже с наценкой,
  // фасады умножим отдельно, поэтому здесь ставим 1.
  safeResult.скрМульт = 1;

  const out = {};
  for (const k of SAFE_TOP) {
    if (data[k] !== undefined) out[k] = data[k];
  }

  // Фасады: отдаём материал/площадь и цену УЖЕ с учётом скрытой наценки
  out.фасады = Array.isArray(data.фасады)
    ? data.фасады.map((f) => ({
        материал: f.материал || '',
        площадь: f.площадь || '',
        цена: (parseFloat(String(f.цена).replace(',', '.')) || 0) * скрМульт,
      }))
    : [];

  out.result = safeResult;

  // Статусы из отдельных колонок (без раскрытия самого отзыва клиенту)
  out.confirmed_at = row.confirmed_at || null;
  out.feedbackSent = !!row.feedback;

  return out;
}

module.exports = { toPublic };
